export function findMatchesForListing(listing: MarketplaceListing | MaterialPassport): MatchRecommendation[] {
  const category = listing.category;
  const quantity = "quantityMT" in listing ? listing.quantityMT : 10;
  const reusability = "reusabilityScore" in listing ? listing.reusabilityScore : 90;
  const listingId = "id" in listing ? listing.id : "LIST-GEN";

  // Filter relevant real-world buyers
  const candidates = INDIAN_BUYERS_DIRECTORY.filter(b => b.acceptedCategories.includes(category));

  return candidates.map((buyer, index) => {
    // Calculate match score
    const categoryFit = 40; // 40 max
    const purityFit = Math.min(30, Math.round((reusability / 100) * 30));
    const distancePenalty = Math.min(20, Math.round((buyer.distanceKm / 200) * 15));
    const distanceFit = Math.max(5, 20 - distancePenalty);
    const capacityRatio = Math.min(1, quantity / buyer.typicalLotCapacityMT);
    const capacityFit = Math.round(capacityRatio * 10);
    const totalScore = Math.min(99, categoryFit + purityFit + distanceFit + capacityFit);

    const freight = estimateFreightCostInr(buyer.distanceKm, quantity);

    return {
      id: `MATCH-${listingId}-${buyer.id}-${index}`,
      listingId,
      buyerOrg: buyer.name,
      buyerType: `${buyer.type} (${buyer.corporateGroup})`,
      industrySector: buyer.industrySector,
      annualCapacityMT: buyer.annualRecyclingCapacityMT,
      buyerCity: buyer.city,
      buyerState: buyer.state,
      spcbJurisdiction: buyer.spcbJurisdiction,
      distanceKm: buyer.distanceKm,
      matchScore: totalScore,
      estimatedFreightInr: freight.estimatedFreightInr,
      buyerFacilityImage: buyer.facilityImageUrl,
      buyerAvatar: buyer.buyerAvatar,
      cleanEnvImage: buyer.cleanEnvImage,
      cleanEnvStat: buyer.cleanEnvStat,
      whyMatch: {
        materialFit: `Direct chemical & metallurgical compatibility for ${buyer.targetFurnaceType}.`,
        quantityFit: `${quantity} MT lot matches their procurement cycle (plant accepts ~${buyer.typicalLotCapacityMT} MT/lot, ${buyer.annualRecyclingCapacityMT.toLocaleString("en-IN")} MT/year total capacity).`,
        gradeCompatibility: `Purity score (${reusability}%) satisfies verified acceptance threshold of ${buyer.minimumPurityRequired}%.`,
        logisticsSummary: `${buyer.distanceKm} km transit (${freight.transitHours} hrs turnaround) to ${buyer.industrialZone} via national highway corridor.`,
        carbonSavingsPotential: `Replaces virgin feedstock while minimizing transit emissions via verified short-radius industrial route.`,
        regulatoryAlignment: `Authorized CPCB/SPCB exchange under ${buyer.spcbJurisdiction} (GSTIN: ${buyer.gstin} • CPCB Reg: ${buyer.cpcbAuthNumber}).`,
      },
      recommendedApplication: `Direct secondary feedstock in ${buyer.name}'s manufacturing cycle (${buyer.industrialZone}).`,
      status: "suggested",
    };
  });
}

